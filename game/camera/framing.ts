/**
 * 화면 모양에 맞춰 카메라를 얼마나 물릴지 정한다.
 *
 * ── 왜 필요한가 ──
 * three 의 `fov` 는 **세로** 화각이다. 그래서 화면이 세로로 길어져도 세로로 보이는
 * 범위는 그대로고, 대신 **가로가 좁아진다**. 가로로 보이는 폭은
 * `2 · 거리 · tan(fov/2) · 종횡비` 라 종횡비에 정비례한다 —
 * 16:9 데스크톱에서 편하던 화면이 세로 폰(0.46)에서는 가로 폭이 4분의 1로 줄어든다.
 * 섬 한가운데 서면 좌우가 캐릭터로 꽉 차서 어디로 가야 할지 안 보인다.
 *
 * ── 왜 종횡비인가, 터치 여부가 아니라 ──
 * "모바일이면 멀리" 로 잡으면 가로로 돌린 폰(종횡비 2.1, 데스크톱보다 넓다)까지
 * 쓸데없이 물러난다. 문제는 기기가 아니라 **화면 모양**이라 종횡비를 본다.
 *
 * ── 왜 제곱근인가 ──
 * 가로 폭을 그대로 유지하려면 거리를 종횡비에 반비례시켜야 하는데(24m → 93m),
 * 그러면 캐릭터가 점이 된다. 제곱근을 쓰면 좁아진 만큼의 절반쯤만 물러나서
 * 좌우가 트이면서도 캐릭터가 남는다. 상한 1.5 는 그 타협의 끝이다.
 */

/** 이 종횡비에서는 물러나지 않는다. 16:10 언저리 — 데스크톱의 기준 화면. */
const REFERENCE_ASPECT = 1.6;

/** 아무리 좁아도 이 배수까지만. 더 물러나면 캐릭터가 점이 된다. */
const MAX_ZOOM_OUT = 1.5;

export function zoomOutForAspect(aspect: number): number {
  // 0 이나 NaN 이 들어오면(첫 프레임의 0px 캔버스 등) 그냥 기준값으로 둔다.
  if (!Number.isFinite(aspect) || aspect <= 0) return 1;
  const ratio = Math.sqrt(REFERENCE_ASPECT / aspect);
  return Math.min(MAX_ZOOM_OUT, Math.max(1, ratio));
}
