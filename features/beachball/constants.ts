import type { Vec2XZ } from "@/shared/types";

/**
 * 비치볼 놀이터. 섬 서쪽 모래밭이다.
 *
 * ── 왜 여기인가 ──
 * 손으로 고른 자리가 아니라 **조건을 만족하는 곳을 찾아서** 정했다.
 *
 *  1. **평평해야 한다.** 공은 굴러가는 물건이라 땅이 기울면 한쪽으로만 간다.
 *     이 섬은 하트라 반지름이 각도마다 두 배씩 차이 나고 지형이 언덕으로
 *     울렁여서, 골대까지 포함한 13×15m 안에서 높이 차가 5mm 인 자리는 드물다.
 *  2. **야자수가 남쪽에 없어야 한다.** 카메라는 방위가 고정이라 늘 북쪽을
 *     보므로, 남쪽에 선 나무는 화면에서 골대 앞을 막는다(island.test 가 지킨다).
 *  3. **다른 볼거리와 겹치지 않아야 한다.** 15m 밖이면 서로 다른 자리다.
 *  4. **스폰 카메라 통로를 비켜야 한다.** 한 번 남쪽 잔디밭(0, 38)에 뒀다가
 *     들어오자마자 **골대가 화면 아래를 가로지르는** 첫 화면이 나왔다.
 *     카메라는 캐릭터 남쪽 22m 에 뜨므로 스폰(0, 21) 의 카메라는 z=43 에
 *     있고, 그 사이 30m 는 첫 화면이 통째로 지나가는 자리다.
 */
export const PITCH_CENTER: Vec2XZ = [-27, 5];

/** 골대의 가운데. 놀이터와 같은 x 다. */
export const GOAL_CENTER_X = PITCH_CENTER[0];

/** 공이 시작하는 자리(골대에서 6m 앞). */
export const BALL_HOME: Vec2XZ = [PITCH_CENTER[0], PITCH_CENTER[1]];

/**
 * 골대.
 *
 * ⚠ 공보다 **북쪽**에 둔다. 카메라는 방위가 고정이라 늘 북쪽을 보므로,
 *   골대가 남쪽에 있으면 넣는 사람은 등 뒤로 차야 하고 화면에는 아무것도
 *   안 보인다. 북쪽이면 공도 골대도 사람 앞이다 — 낚시터를 옆으로 돌려
 *   놓은 것과 같은 이유다.
 */
export const GOAL_Z = PITCH_CENTER[1] - 7;
/** 골대 기둥 사이의 절반 폭(m). */
export const GOAL_HALF = 2.6;
export const GOAL_HEIGHT = 2.4;

export const BALL_RADIUS = 0.42;

/** 사람이 공에 닿았다고 볼 거리. 반지름 + 어깨 너비쯤. */
export const KICK_REACH = BALL_RADIUS + 0.75;
/** 한 번 찬 뒤 다시 찰 수 있을 때까지(초). 없으면 공이 발에 붙어 끌려간다. */
export const KICK_COOLDOWN = 0.35;
